#!/usr/bin/env python3
"""
EDU01 R1 — Step 20: bibliometric indicators + LaTeX number macros
=================================================================
Input : data/wave_yearly.csv, wave_matches.csv, pool_yearly.csv,
        validation_precision.csv / validation_nearmiss.csv (manually coded),
        openalex_title_abstract_yearly.csv
Output: data/bib_summary.csv, R1/manuscript/numbers_bib.tex
Every number quoted in the bibliometric part of the R1 manuscript comes from
the macros written here.
"""
import csv, json, math
from collections import defaultdict
from pathlib import Path
from scipy.stats import spearmanr

ROOT = Path(__file__).resolve().parents[1]
V2 = ROOT / "data"
TEX = ROOT / "manuscript" / "numbers_bib.tex"
CORE_EXCLUDE = {"ACCESS", "IoT-J"}  # broad, fast-growing journals that dominate the pool
TAG = {"ai_hardware": "AI", "neuromorphic": "NE", "iot_security": "SE", "quantum_hw": "QU"}


def wilson(k, n, z=1.96):
    if n == 0:
        return float("nan"), float("nan")
    p = k / n
    d = 1 + z * z / n
    c = (p + z * z / (2 * n)) / d
    h = z * math.sqrt(p * (1 - p) / n + z * z / (4 * n * n)) / d
    return c - h, c + h


def fmt(x, nd=0):
    s = f"{x:,.{nd}f}"
    return s.replace(",", "\\,")


def main():
    yearly = defaultdict(dict)
    for r in csv.DictReader(open(V2 / "wave_yearly.csv")):
        yearly[r["wave"]][int(r["year"])] = (int(r["n"]), int(r["pool_total"]), float(r["share_pct"]))
    oa = defaultdict(dict)
    for r in csv.DictReader(open(V2 / "openalex_title_abstract_yearly.csv")):
        oa[r["wave"]][int(r["year"])] = float(r["share_pct"])
    teduc = defaultdict(int)
    for r in csv.DictReader(open(V2 / "wave_matches.csv")):
        if r["journal"] == "T-EDUC":
            for w in r["waves"].split(";"):
                teduc[w] += 1
    teduc_total = sum(int(r["n_articles"]) for r in csv.DictReader(open(V2 / "pool_yearly.csv"))
                      if r["journal"] == "T-EDUC")
    prec, miss = defaultdict(list), defaultdict(list)
    for r in csv.DictReader(open(V2 / "validation_precision.csv")):
        if r["relevant(1/0)"].strip() in ("0", "1"):
            prec[r["wave"]].append(int(r["relevant(1/0)"]))
    for r in csv.DictReader(open(V2 / "validation_nearmiss.csv")):
        if r["should_match(1/0)"].strip() in ("0", "1"):
            miss[r["wave"]].append(int(r["should_match(1/0)"]))

    pool = {y: v[1] for y, v in yearly["ai_hardware"].items()}
    nm_pool = json.loads((V2 / "nearmiss_pool_sizes.json").read_text())
    core_tot, core_n = defaultdict(int), defaultdict(lambda: defaultdict(int))
    for r in csv.DictReader(open(V2 / "pool_yearly.csv")):
        if r["journal"] not in CORE_EXCLUDE:
            core_tot[int(r["year"])] += int(r["n_articles"])
    for r in csv.DictReader(open(V2 / "wave_matches.csv")):
        if r["journal"] not in CORE_EXCLUDE:
            for w in r["waves"].split(";"):
                core_n[w][int(r["year"])] += 1
    lines = [f"% generated by scripts/20_bib_indicators.py — do not edit",
             f"\\newcommand{{\\PoolN}}{{{fmt(sum(pool.values()))}}}",
             f"\\newcommand{{\\PoolA}}{{{fmt(pool[2015])}}}",
             f"\\newcommand{{\\PoolB}}{{{fmt(pool[2025])}}}",
             f"\\newcommand{{\\PoolG}}{{{pool[2025] / pool[2015]:.1f}}}",
             f"\\newcommand{{\\TeducN}}{{{fmt(teduc_total)}}}"]
    summary = []
    for wave, t in TAG.items():
        y = yearly[wave]
        a, b = y[2015][0], y[2025][0]
        sa, sb = y[2015][2], y[2025][2]
        tot = sum(v[0] for v in y.values())
        yrs = sorted(y)
        rho = spearmanr([y[k][2] for k in yrs], [oa[wave][k] for k in yrs]).correlation
        p = prec[wave]; m = miss[wave]
        plo, phi = wilson(sum(p), len(p))
        tp = tot * sum(p) / len(p)
        fn = nm_pool[wave] * sum(m) / len(m)
        recall = tp / (tp + fn)
        ca = 100 * core_n[wave][2015] / core_tot[2015]
        cb = 100 * core_n[wave][2025] / core_tot[2025]
        lines += [f"\\newcommand{{\\n{t}a}}{{{fmt(a)}}}", f"\\newcommand{{\\n{t}b}}{{{fmt(b)}}}",
                  f"\\newcommand{{\\n{t}tot}}{{{fmt(tot)}}}",
                  f"\\newcommand{{\\g{t}}}{{{b / a:.1f}}}" if a else f"\\newcommand{{\\g{t}}}{{n/a}}",
                  f"\\newcommand{{\\s{t}a}}{{{sa:.2f}}}", f"\\newcommand{{\\s{t}b}}{{{sb:.2f}}}",
                  f"\\newcommand{{\\sg{t}}}{{{sb / sa:.1f}}}" if sa else f"\\newcommand{{\\sg{t}}}{{n/a}}",
                  f"\\newcommand{{\\rho{t}}}{{{rho:.2f}}}",
                  f"\\newcommand{{\\teduc{t}}}{{{teduc[wave]}}}",
                  f"\\newcommand{{\\precn{t}}}{{{len(p)}}}",
                  f"\\newcommand{{\\preck{t}}}{{{sum(p)}}}",
                  f"\\newcommand{{\\prec{t}}}{{{100 * sum(p) / len(p):.0f}}}" if p else "",
                  f"\\newcommand{{\\prec{t}lo}}{{{100 * plo:.0f}}}" if p else "",
                  f"\\newcommand{{\\prec{t}hi}}{{{100 * phi:.0f}}}" if p else "",
                  f"\\newcommand{{\\missn{t}}}{{{len(m)}}}", f"\\newcommand{{\\missk{t}}}{{{sum(m)}}}",
                  f"\\newcommand{{\\rec{t}}}{{{100 * recall:.0f}}}",
                  f"\\newcommand{{\\cs{t}a}}{{{ca:.2f}}}", f"\\newcommand{{\\cs{t}b}}{{{cb:.2f}}}",
                  f"\\newcommand{{\\csg{t}}}{{{cb / ca:.1f}}}" if ca else f"\\newcommand{{\\csg{t}}}{{n/a}}"]
        summary.append([wave, a, b, tot, round(b / a, 2) if a else "", sa, sb,
                        round(sb / sa, 2) if sa else "", round(rho, 3), teduc[wave],
                        f"{sum(p)}/{len(p)}", f"{sum(m)}/{len(m)}", round(recall, 3),
                        round(ca, 3), round(cb, 3), round(cb / ca, 2) if ca else ""])
    TEX.parent.mkdir(parents=True, exist_ok=True)
    TEX.write_text("\n".join(l for l in lines if l) + "\n")
    with open(V2 / "bib_summary.csv", "w", newline="") as f:
        w = csv.writer(f)
        w.writerow(["wave", "n2015", "n2025", "n_total", "abs_growth", "share2015_pct", "share2025_pct",
                    "share_growth", "spearman_title_vs_title_abstract", "teduc_articles",
                    "precision_k/n", "nearmiss_should_match_k/n", "recall_est",
                    "core_share2015_pct", "core_share2025_pct", "core_share_growth"])
        w.writerows(summary)
    for s in summary:
        print(s)



def windows():
    """3-year pooled windows (2015-17 vs 2023-25): whole pool, core pool, core pool without T-QE."""
    pools = {"all": set(), "core": {"ACCESS", "IoT-J"}, "coreQE": {"ACCESS", "IoT-J", "T-QE"}}
    A, B = (2015, 2016, 2017), (2023, 2024, 2025)
    tot = {k: defaultdict(int) for k in pools}
    cnt = {k: defaultdict(lambda: defaultdict(int)) for k in pools}
    for r in csv.DictReader(open(V2 / "pool_yearly.csv")):
        for k, ex in pools.items():
            if r["journal"] not in ex:
                tot[k][int(r["year"])] += int(r["n_articles"])
    for r in csv.DictReader(open(V2 / "wave_matches.csv")):
        for k, ex in pools.items():
            if r["journal"] not in ex:
                for w in r["waves"].split(";"):
                    cnt[k][w][int(r["year"])] += 1
    lines, out = [], []
    for k in pools:
        for wave, t in TAG.items():
            sa = 100 * sum(cnt[k][wave][y] for y in A) / sum(tot[k][y] for y in A)
            sb = 100 * sum(cnt[k][wave][y] for y in B) / sum(tot[k][y] for y in B)
            na, nb = sum(cnt[k][wave][y] for y in A), sum(cnt[k][wave][y] for y in B)
            tag = {"all": "w", "core": "wc", "coreQE": "wq"}[k]
            lines += [f"\\newcommand{{\\{tag}{t}a}}{{{sa:.2f}}}", f"\\newcommand{{\\{tag}{t}b}}{{{sb:.2f}}}",
                      f"\\newcommand{{\\{tag}g{t}}}{{{sb / sa:.1f}}}",
                      f"\\newcommand{{\\{tag}n{t}a}}{{{na}}}", f"\\newcommand{{\\{tag}n{t}b}}{{{nb}}}"]
            out.append([k, wave, na, nb, round(sa, 3), round(sb, 3), round(sb / sa, 2)])
    with open(V2 / "bib_windows.csv", "w", newline="") as f:
        w = csv.writer(f); w.writerow(["pool", "wave", "n_2015_17", "n_2023_25", "share_2015_17_pct",
                                       "share_2023_25_pct", "share_ratio"]); w.writerows(out)
    with open(TEX, "a") as f:
        f.write("\n".join(lines) + "\n")
    for o in out:
        print(o)



if __name__ == "__main__":
    main()
    windows()
