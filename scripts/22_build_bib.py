def tex(s):
    s = html.unescape(re.sub(r"<[^>]+>", "", s))
    for a, b in (("&", r"\&"), ("%", r"\%"), ("_", r"\_"), ("#", r"\#")):
        s = s.replace(a, b)
    return re.sub(r"\s+", " ", s).strip()


def entry(key, doi):
    r = requests.get(f"https://api.crossref.org/works/{doi}", headers=H, timeout=60)
    r.raise_for_status()
    w = r.json()["message"]
    names = []
    for a in w.get("author", []):
        if "family" in a:
            names.append(f"{tex(a['family'])}, {tex(a.get('given', ''))}".rstrip(", "))
        elif "name" in a:
            names.append("{" + tex(a["name"]) + "}")
    if not names and w.get("editor"):
        names = [f"{tex(a['family'])}, {tex(a.get('given', ''))}" for a in w["editor"] if "family" in a]
    year = (w.get("published-print") or w.get("published-online") or w["issued"])["date-parts"][0][0]
    f = {"author": " and ".join(names) if names else None, "title": "{" + tex(w["title"][0]) + "}",
         "year": str(year), "doi": w["DOI"], "url": "https://doi.org/" + w["DOI"]}
    typ = w.get("type")
    cont = tex((w.get("container-title") or [""])[0])
    if typ == "journal-article":
        kind = "article"
        f.update(journal=cont, volume=w.get("volume"), number=w.get("issue"),
                 pages=(w.get("page") or w.get("article-number") or "").replace("-", "--") or None)
    elif typ == "proceedings-article":
        kind = "inproceedings"
        f.update(booktitle=cont, volume=w.get("volume"), number=w.get("issue"),
                 pages=(w.get("page") or "").replace("-", "--") or None)
    else:
        kind = "book"
        f.update(publisher=tex(w.get("publisher", "")))
    if not names and kind == "book":
        f["author"] = "{" + "ACM/IEEE-CS/AAAI Joint Task Force on Computing Curricula" + "}"
    body = ",\n".join(f"  {k} = {{{v}}}" for k, v in f.items() if v)
    return f"@{kind}{{{key},\n{body}\n}}\n", len(names), w["title"][0]


def main():
    out = ["% generated by scripts/22_build_bib.py from Crossref — do not edit by hand\n"]
    for key, doi in REFS.items():
        e, n, t = entry(key, doi)
        out.append(e)
        print(f"{key:26s} authors={n:2d}  {t[:70]}")
        time.sleep(0.4)
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(out))


if __name__ == "__main__":
    main()
